public class MataKuliah {
    String kode;
    String nama;
    int sks;
    int semester;
    String periode;


    public MataKuliah (String kode, String nama, int sks, int semester, String periode) {
        this.kode = kode;
        this.nama = nama;
        this.sks = sks;
        this.semester = semester;
        this.periode = periode;
    }
    
}
